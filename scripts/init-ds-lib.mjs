/**
 * The rename mechanics behind `pnpm init-ds`, kept apart from the CLI so each step can be tested
 * on a temporary tree rather than on this repository.
 */

import { existsSync, readFileSync, readdirSync, rmdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

/**
 * Directories the traversal never enters.
 *
 * Skip by denylist, never by an allowlist of dot-directories. An earlier allowlist covered known
 * tool directories but silently missed apps/storybook/.storybook, leaving imports under the old
 * package scope. With a denylist, new directories are renamed by default.
 */
export const SKIP_DIRS = new Set([
  'node_modules',
  'browser-generated',
  '.git',
  'dist',
  'build',
  '.vite',
  '.turbo',
  'storybook-static',
  'coverage',
]);

/**
 * Files the rename never rewrites.
 *
 * The codemod files contain the rules themselves; rewriting them would corrupt the running tool
 * and make its result depend on traversal order. The lockfile is regenerated by `pnpm install`
 * after package manifests move, rather than being edited as text.
 */
export const SKIP_FILES = new Set([
  'scripts/init-ds.mjs',
  'scripts/init-ds-lib.mjs',
  'pnpm-lock.yaml',
]);

/**
 * File extensions the rename reads.
 *
 * Missing a source extension creates exactly the silent half-rename this tool prevents. `.vue`
 * was added with the Vue backend after generated SFCs retained old imports and data attributes.
 * Adding a backend means reviewing this list.
 */
export const EXTENSIONS = new Set([
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.json',
  '.css',
  '.md',
  '.html',
  '.vue',
  '.yaml',
  '.yml',
]);

const NAME_PATTERN = /^[a-z][a-z0-9]*$/;

/**
 * Whether a string is usable as the identity: it becomes an npm scope, a CSS custom-property
 * namespace and a data-attribute prefix, so it is lowercase letters and digits after a letter.
 *
 * @param {unknown} name
 * @returns {boolean}
 */
export function validName(name) {
  return typeof name === 'string' && NAME_PATTERN.test(name);
}

/**
 * Check that a parsed `ds.config.json` says one thing in all four fields: `scope`, `tokenPrefix`
 * and `dataPrefix` must agree with `name`. A disagreement is a half-renamed repository, which
 * builds green and is wrong, so the CLI refuses to work from one.
 *
 * @param {unknown} config - the parsed ds.config.json
 * @returns {string[]} one message per problem; empty when the identity is consistent
 */
export function identityProblems(config) {
  if (!config || typeof config !== 'object' || Array.isArray(config)) {
    return ['ds.config.json must contain an object.'];
  }

  const problems = [];
  if (!validName(config.name)) {
    problems.push(
      `name must be lowercase letters and digits, starting with a letter; received ${JSON.stringify(config.name)}.`,
    );
    return problems;
  }

  for (const [field, expected] of [
    ['scope', `@${config.name}`],
    ['tokenPrefix', config.name],
    ['dataPrefix', config.name],
  ]) {
    if (config[field] !== expected) {
      problems.push(
        `${field} is ${JSON.stringify(config[field])}; expected ${JSON.stringify(expected)}.`,
      );
    }
  }
  return problems;
}

/**
 * The custom-element tag names a rename has to move, as kebab-case component names.
 *
 * Contracts are the authoritative component inventory. Deriving tags from them avoids a broad
 * prefix rule that would also rename agent-tooling names such as `ds-decide`.
 *
 * @param {string} root - repository root
 * @returns {string[]} sorted tag names, empty when no contract exists yet
 */
export function componentTags(root) {
  const dir = join(root, 'packages/contracts/components');
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase())
    .sort();
}

/**
 * The rename rules: data attributes, package scope, custom properties, prefixed identifiers such
 * as Angular selectors, and component tags. They do not overlap — the tag rule's lookbehind is
 * what keeps it out of `data-<prefix>-button`, so the order below is for reading, not correctness.
 *
 * @param {string} from - the current prefix
 * @param {string} name - the new prefix
 * @param {string[]} tags - component tags from `componentTags`
 * @returns {Array<[RegExp, string]>} pattern/replacement pairs
 */
export function buildRules(from, name, tags) {
  return [
    [new RegExp(`data-${from}-`, 'g'), `data-${name}-`],
    [new RegExp(`@${from}/`, 'g'), `@${name}/`],
    [new RegExp(`--${from}-`, 'g'), `--${name}-`],
    // `String.raw` is required: in a normal template literal `\b` becomes a backspace character,
    // so the rule silently matches nothing. Prefix+capital identifiers are reserved for Angular
    // selectors and other generated identifiers in this family.
    [new RegExp(String.raw`\b${from}(?=[A-Z])`, 'g'), name],
    // A component tag also namespaces related identifiers such as ds-button-spin, so the match
    // ends at the tag rather than at a word boundary. The lookbehind rejects a prefix that is
    // itself the tail of a longer word or hyphenated name, which is what keeps it out of
    // `data-<prefix>-button` and anything of the form `<something>-<prefix>-button`.
    ...(tags.length
      ? [[new RegExp(String.raw`(?<![\w-])${from}-(?=(?:${tags.join('|')})\b)`, 'g'), `${name}-`]]
      : []),
  ];
}

/**
 * Apply every rule to one file's text, in order.
 *
 * @param {string} text
 * @param {Array<[RegExp, string]>} rules
 * @returns {string}
 */
export function applyRules(text, rules) {
  let result = text;
  for (const [pattern, replacement] of rules) result = result.replace(pattern, replacement);
  return result;
}

/**
 * Count a pattern's matches without consuming the caller's global regex state.
 *
 * @param {string} text
 * @param {RegExp} pattern
 * @returns {number}
 */
function countMatches(text, pattern) {
  return [...text.matchAll(new RegExp(pattern.source, pattern.flags))].length;
}

/**
 * Yield every renameable file under `root`, sorted, skipping `SKIP_DIRS` and nested checkouts.
 *
 * @param {string} root
 * @param {string} [dir] - the directory being visited; defaults to `root`
 * @yields {string} absolute file path
 */
export function* walk(root, dir = root) {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name < b.name ? -1 : 1,
  )) {
    if (SKIP_DIRS.has(entry.name)) continue;

    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      // A nested repository or worktree belongs to another checkout. Its .git may be a directory
      // or a gitdir file; either form is a hard traversal boundary.
      if (existsSync(join(full, '.git'))) continue;
      yield* walk(root, full);
    } else if (EXTENSIONS.has(entry.name.slice(entry.name.lastIndexOf('.')))) {
      yield full;
    }
  }
}

/**
 * Work out the whole rename before writing any of it, so a failure has something to roll back to.
 *
 * @param {string} root
 * @param {Array<[RegExp, string]>} rules
 * @returns {Array<{file: string, path: string, before: string, after: string, hits: number}>}
 *   one entry per file whose text changes, with `file` relative and slash-separated
 */
export function planRenames(root, rules) {
  const changed = [];
  for (const file of walk(root)) {
    const relativePath = relative(root, file).split('\\').join('/');
    if (SKIP_FILES.has(relativePath)) continue;

    const before = readFileSync(file, 'utf8');
    const after = applyRules(before, rules);
    if (after !== before) {
      changed.push({
        file: relativePath,
        path: file,
        before,
        after,
        hits: rules.reduce((total, [pattern]) => total + countMatches(before, pattern), 0),
      });
    }
  }
  return changed;
}

/**
 * Write a plan from `planRenames` to disk.
 *
 * @param {Array<{path: string, after: string}>} changed
 */
export function writeRenamePlan(changed) {
  for (const change of changed) writeFileSync(change.path, change.after);
}

/**
 * Plan and, unless `dry`, apply a rename in one call.
 *
 * @param {string} root
 * @param {Array<[RegExp, string]>} rules
 * @param {{dry?: boolean}} [options]
 * @returns {ReturnType<typeof planRenames>} the plan, written or not
 */
export function renameTree(root, rules, { dry = false } = {}) {
  const changed = planRenames(root, rules);
  if (!dry) writeRenamePlan(changed);
  return changed;
}

/**
 * Record the current contents of every path the run may touch, including paths that do not exist
 * yet — restoring one of those means deleting it again.
 *
 * @param {string[]} paths
 * @returns {Map<string, {existed: boolean, contents: Buffer | null}>}
 */
export function snapshotPaths(paths) {
  const snapshot = new Map();
  for (const path of new Set(paths.map((path) => resolve(path)))) {
    const existed = existsSync(path);
    snapshot.set(path, {
      existed,
      contents: existed ? readFileSync(path) : null,
    });
  }
  return snapshot;
}

/**
 * Put every snapshotted path back as it was. It reports what it could not restore rather than
 * throwing, because it runs while another failure is already being handled.
 *
 * @param {ReturnType<typeof snapshotPaths>} snapshot
 * @returns {string[]} one message per path that could not be restored
 */
export function restoreSnapshot(snapshot) {
  const failures = [];
  for (const [path, state] of snapshot) {
    try {
      if (state.existed) writeFileSync(path, state.contents);
      else rmSync(path, { force: true });
    } catch (error) {
      failures.push(`${path}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  return failures;
}

/**
 * Remove, deepest first, the directories this run created. Directories that already existed are
 * left alone, and so is anything that is no longer empty.
 *
 * @param {Array<{path: string, existed: boolean}>} directories - recorded before the run
 * @returns {string[]} one message per directory that could not be removed
 */
export function removeCreatedDirectories(directories) {
  const failures = [];
  for (const directory of [...directories].reverse()) {
    if (directory.existed || !existsSync(directory.path)) continue;
    try {
      rmdirSync(directory.path);
    } catch (error) {
      failures.push(`${directory.path}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  return failures;
}
